import { readFile, writeFile } from "node:fs/promises";

const sharedRoot = "public/proposta-partner/shared/";
const translations = JSON.parse(await readFile(`${sharedRoot}translations.json`, "utf8"));
const templates = Object.fromEntries(await Promise.all(["header", "menu", "language", "footer"].map(async (name) => [name, await readFile(`src/shared/${name}.html`, "utf8")])));
const socials = await readFile("src/shared/socials.html", "utf8");
const escape = (value) => String(value).replaceAll("&", "&amp;").replaceAll('"', "&quot;").replaceAll("<", "&lt;").replaceAll(">", "&gt;");

export const navigation = [
  { path:"/about/", key:"navAbout" },
  { path:"/projects/pandanna/", key:"navPandanna" },
  { path:"/projects/pandanna/gallery/", key:"gallery" },
  { path:"/maps/", key:"maps" }
];
export const publicPages = {
  "/404.html": { name:"error", indexable:false },
  "/": { name:"home" },
  "/about/": { name:"about" },
  "/projects/pandanna/": { name:"pandanna" },
  "/projects/pandanna/gallery/": { name:"gallery", indexable:false, back:"/projects/pandanna/", backKey:"backToPandanna" },
  "/maps/": { name:"maps", back:"/projects/pandanna/", backKey:"backToPandanna" }
};

export async function buildTranslationData() {
  // Generated browser data; translations.json is the only editable text source.
  await writeFile(`${sharedRoot}translations.js`, `// Generated by npm run build from shared/translations.json.\nwindow.PANDA_TRANSLATIONS = ${JSON.stringify(translations, null, 2)};\n`, "utf8");
}

export function renderLayout(html, { path = "/" } = {}) {
  const page = publicPages[path];
  if (!page) throw new Error(`Pagina senza configurazione di navigazione: ${path}`);
  const current = (destination) => destination === path ? ' aria-current="page"' : "";
  const links = (items, className) => items.map((item) => `<a class="${className}" href="${item.path}" data-i18n="${item.key}"${current(item.path)}>{{t:${item.key}}}</a>`).join("\n");
  const slots = {
    skipTarget: path === "/404.html" ? "#main-content" : `${path}#main-content`,
    back: page.back ? `<a class="map-back" href="${page.back}" data-page-return data-i18n="${page.backKey}">{{t:${page.backKey}}}</a>` : "",
    brandCurrent: current("/"),
    navigation: links(navigation, "site-navigation__link"),
    menuNavigation: links([{ path:"/", key:"home" }, ...navigation], "site-menu__link"),
    footerNavigation: links(navigation, "site-footer__link"),
    socials,
    languages: Object.entries(translations.languages).map(([code, language]) => `<button class="language-option" type="button" data-language="${escape(code)}">${escape(language.native)}<span>${escape(code.toUpperCase())}</span></button>`).join("")
  };
  for (const name of Object.keys(templates)) {
    const marker = `<!-- site:${name} -->`;
    if (html.split(marker).length !== 2) throw new Error(`Include ${name} mancante o duplicato`);
    const markup = templates[name].replace(/\{\{(skipTarget|back|brandCurrent|navigation|menuNavigation|footerNavigation|socials|languages)\}\}/g, (_, key) => slots[key]).replace(/\{\{t:(\w+)\}\}/g, (_, key) => {
      if (!(key in translations.copy.it)) throw new Error(`Testo del layout mancante: ${key}`);
      return escape(translations.copy.it[key]);
    });
    html = html.replace(marker, markup);
  }
  return html.replace(/<meta name="robots" content="[^"]*"\s*\/>/, `<meta name="robots" content="${page.indexable === false ? "noindex" : "index"}, follow" />`).replace(/<main\b/, '<main id="main-content" tabindex="-1"').replace(/<body\b/, `<body data-page="${page.name}"${page.back ? " data-has-page-return" : ""}`).replace(/[\t ]+$/gm, "");
}
